// Package opsgen turns the Unrent API's OpenAPI 3.1 document into the provider's operation table (ops_gen.go).
package opsgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"
)

type operation struct {
	OperationID string                     `json:"operationId"`
	Scope       string                     `json:"x-unrent-scope"`
	Responses   map[string]json.RawMessage `json:"responses"`
}

type document struct {
	OpenAPI string `json:"openapi"`
	Info    struct {
		Version string `json:"version"`
	} `json:"info"`
	Paths map[string]map[string]operation `json:"paths"`
}

// Generate returns the gofmt'ed Go source of ops_gen.go for an OpenAPI document.
func Generate(doc []byte) ([]byte, error) {
	var d document
	if err := json.Unmarshal(doc, &d); err != nil {
		return nil, err
	}
	if !strings.HasPrefix(d.OpenAPI, "3.1") {
		return nil, fmt.Errorf("openapi %q: want 3.1", d.OpenAPI)
	}
	type row struct {
		name, id, method, path, scope string
		approval                      bool
	}
	var rows []row
	seen := map[string]bool{}
	for path, ops := range d.Paths {
		for method, op := range ops {
			if op.OperationID == "" {
				return nil, fmt.Errorf("%s %s: no operationId", method, path)
			}
			if seen[op.OperationID] {
				return nil, fmt.Errorf("duplicate operationId %s", op.OperationID)
			}
			seen[op.OperationID] = true
			_, approval := op.Responses["202"]
			rows = append(rows, row{"Op" + export(op.OperationID), op.OperationID, strings.ToUpper(method), path, op.Scope, approval})
		}
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].name < rows[j].name })
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/client/gen from the Unrent API's OpenAPI document; DO NOT EDIT.\n\npackage client\n\n")
	fmt.Fprintf(&b, "// APIVersion is the version of the OpenAPI document these operations come from.\nconst APIVersion = %q\n\n", d.Info.Version)
	b.WriteString("// Operations of the Unrent API (https://api.unrent.dev/v1), by operationId.\nvar (\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t%s = Operation{ID: %q, Method: %q, Path: %q, Scope: %q, Approval: %t}\n", r.name, r.id, r.method, r.path, r.scope, r.approval)
	}
	b.WriteString(")\n\n// AllOperations lists every operation of the document.\nvar AllOperations = []Operation{\n")
	for _, r := range rows {
		fmt.Fprintf(&b, "\t%s,\n", r.name)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func export(id string) string {
	r := []rune(id)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}
